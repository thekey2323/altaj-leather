// Helper function to create relative ISO dates
const daysAgo = (days: number, hoursOffset: number = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(d.getHours() - hoursOffset);
  return d.toISOString();
};

